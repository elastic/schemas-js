/**
 * Writes src/<category>/tools/json-manifest.ts: the list of JSON sidecar
 * schema filenames generated into src/<category>/json/.
 *
 * Downstream consumers (e.g. elastic/cli, embedding this package into a
 * `bun build --compile` binary) need the exact filenames as string literals
 * to write literal `import()` calls, and previously had to enumerate this
 * package's installed directory tree themselves to get them. Run as part of
 * `npm run generate` so the manifest can never drift from the files it
 * describes.
 */
import { readdir, writeFile } from 'node:fs/promises'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(repoRoot, 'src')

export const JSON_MANIFEST_CATEGORIES = ['es', 'kibana', 'cloud', 'serverless']

function quoteFilename (file) {
  return `'${file.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

export async function writeJsonManifest (category) {
  const jsonDir = join(srcDir, category, 'json')
  const files = (await readdir(jsonDir)).filter((f) => f.endsWith('.json')).sort()

  const lines = [
    '/*',
    ' * Copyright Elasticsearch B.V. and contributors',
    ' * SPDX-License-Identifier: Apache-2.0',
    ' */',
    '',
    `// Generated by scripts/generate-json-manifest.mjs from src/${category}/json/. Do not edit.`,
    `export const ${category}JsonManifest: readonly string[] = [`,
    ...files.map((f) => `  ${quoteFilename(f)},`),
    ']',
    '',
  ]

  const out = join(srcDir, category, 'tools', 'json-manifest.ts')
  await writeFile(out, lines.join('\n'))
  return { category, count: files.length, out }
}

export async function writeAllJsonManifests () {
  return Promise.all(JSON_MANIFEST_CATEGORIES.map(writeJsonManifest))
}

const entry = process.argv[1]
if (entry != null && import.meta.url === pathToFileURL(resolve(entry)).href) {
  for (const result of await writeAllJsonManifests()) {
    process.stdout.write(`wrote ${result.count} entries to ${result.out}\n`)
  }
}
